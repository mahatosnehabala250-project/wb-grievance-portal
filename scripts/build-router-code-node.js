// Read the TypeScript source
let source = fs.readFileSync(INPUT, 'utf8');

// --- Step 1: Strip TypeScript-only constructs ---

// Remove export interface blocks (multi-line)
source = source.replace(/export\s+interface\s+\w+\s*\{[^}]*\}/gs, '');

// Remove inline type annotations from function parameters and return types
// e.g., `: RouterDecision` after function params, `: boolean` after params
// Remove `: Type` from variable declarations and function params
source = source.replace(/:\s*(RouterDecision|SessionInput|MessageInput|string|number|boolean|Date|RegExp\[\])\s*(?=[,\)=\{;])/g, '');

// Remove return type annotations from functions (`: ReturnType {`)
source = source.replace(/\)\s*:\s*\w+(?:\[\])?\s*\{/g, ') {');

// Remove `export` keywords (we'll wrap everything in an IIFE)
source = source.replace(/^export\s+/gm, '');

// Remove type assertions `as Type`
