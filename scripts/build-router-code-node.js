// Remove generic type parameters from const declarations
// e.g., `const KEYWORDS: { blood: RegExp[]; ... } = {` → `const KEYWORDS = {`
source = source.replace(/const\s+(\w+)\s*:\s*\{[^}]*\}\s*=/gs, 'const $1 =');

// Remove `| null` and `| undefined` type unions in annotations that remain
source = source.replace(/\|\s*(null|undefined)/g, '');

// Remove remaining type annotations on parameters like `(text: string, patterns: RegExp[])`
source = source.replace(/(\w+)\s*:\s*(?:string|number|boolean|Date|RegExp\[\]|RegExp)(?:\s*\|\s*(?:null|undefined))?/g, '$1');

// Remove default type parameter `= new Date()`  → keep as-is (valid JS)
// These are already valid JS defaults, no change needed.

// Remove the JSDoc @see lines that reference .kiro paths (optional cleanup)
// Keep them — they're just comments.

// Remove blank lines that are more than 2 consecutive
source = source.replace(/\n{3,}/g, '\n\n');

