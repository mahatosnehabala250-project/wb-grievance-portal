#!/usr/bin/env node
/* eslint-disable no-console */
// =============================================================================
// register-prompt-versions.js
//   Spec: sahayak-multi-agent-router — task 28.4 (Compact-mode prompt registration)
//   Design §v1.1.11 (Token Budget per Session) / Req 30.5
// =============================================================================
// Registers BOTH the `full` and `compact` prompt variants for each of the four
// specialist agents (complaint, blood, donor, info) into `agent_prompt_versions`
// so the v1.1.14 prompt loader (`src/lib/abtest/promptLoader.ts`) can select the
// compact variant when the v1.1.11 BudgetGuard puts a session into compact mode.
//
// Source of truth = the markdown files under n8n-workflows/prompts/:
//   full    -> <agent>.md
//   compact -> <agent>.compact.md
// These are the same files deploy-workflows-v2.js injects into the JS-01v2
// workflow nodes, so the DB copy never drifts from the deployed prompt text.
//
// The row-building logic lives in src/lib/abtest/promptRegistry.ts and is unit
// tested without a DB. This script is the thin I/O wrapper: it reads the files,
// then idempotently UPSERTs each row keyed on UNIQUE (agent, version).
//
// Usage:
//   node scripts/register-prompt-versions.js                 # upsert into the DB
//   node scripts/register-prompt-versions.js --dry-run       # print rows, no DB write
//   node scripts/register-prompt-versions.js --emit-sql=PATH # write idempotent SQL, no DB write
//                                                            # (run it via psql / Supabase / MCP)
//
// Connection string resolution order (same as tests/migrations/run-smoke.js):
//   1. process.env.SMOKE_DATABASE_URL
//   2. process.env.DIRECT_URL
//   3. process.env.DATABASE_URL
//
// If only the repo's `supabase://use-rest-api` sentinel is present (no direct
// Postgres URL), the script prints a clear SKIP message and exits 0 so it never
// breaks REST-only pipelines. Pass --dry-run to validate the prompt files and
// preview the rows without any DB connection.
//
// Exit codes:
//   0  rows registered, dry-run completed, or skipped (no direct DB URL)
//   1  a prompt file was missing/empty, or the upsert failed
// =============================================================================

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PROMPTS_DIR = path.join(ROOT, 'n8n-workflows', 'prompts');
const SENTINEL = 'supabase://use-rest-api';

// --- Inline mirror of src/lib/abtest/promptRegistry.ts -----------------------
// The TS module is the tested source of truth, but this CLI runs under plain
// node (no ts-node in the deploy path), so the small pure helpers are mirrored
// here. Keep these in sync with promptRegistry.ts.

const AGENTS = ['complaint', 'blood', 'donor', 'info'];
const VERSIONS = ['full', 'compact'];

function promptFileName(agent, version) {
  return version === 'full' ? `${agent}.md` : `${agent}.${version}.md`;
}

const UPSERT_SQL = `
INSERT INTO agent_prompt_versions (agent, version, prompt_md, weight, active, status)
VALUES ($1, $2, $3, $4, $5, $6)
ON CONFLICT (agent, version)
DO UPDATE SET
  prompt_md  = EXCLUDED.prompt_md,
  weight     = EXCLUDED.weight,
  active     = EXCLUDED.active,
  status     = EXCLUDED.status,
  updated_at = NOW()
`.trim();

function buildRows() {
  const rows = [];
  for (const agent of AGENTS) {
    for (const version of VERSIONS) {
      const fileName = promptFileName(agent, version);
      const filePath = path.join(PROMPTS_DIR, fileName);
      let content;
      try {
        content = fs.readFileSync(filePath, 'utf8');
      } catch (err) {
        throw new Error(`missing prompt file "${fileName}" (${filePath}): ${err.message}`);
      }
      if (!content || content.trim().length === 0) {
        throw new Error(`prompt file "${fileName}" is empty`);
      }
      rows.push({ agent, version, prompt_md: content, weight: 1, active: true, status: 'active' });
    }
  }
  return rows;
}

function resolveConnectionString() {
  const candidates = [
    process.env.SMOKE_DATABASE_URL,
    process.env.DIRECT_URL,
    process.env.DATABASE_URL,
  ];
  for (const c of candidates) {
    if (c && c.trim() && c.trim() !== SENTINEL) return c.trim();
  }
  return null;
}

/**
 * Pick a dollar-quote tag that does not occur in `body`, so the prompt markdown
 * (which contains backticks, `$`, quotes, etc.) is embedded verbatim and safely.
 */
function dollarTag(body) {
  let tag = '$prompt$';
  let n = 0;
  while (body.includes(tag)) {
    n += 1;
    tag = `$prompt${n}$`;
  }
  return tag;
}

function emitSql(rows) {
  const lines = [
    '-- Auto-generated by scripts/register-prompt-versions.js (task 28.4).',
    '-- Idempotent: re-running overwrites prompt_md / re-activates each row.',
    '-- Registers full + compact prompt variants for all four specialist agents.',
    'BEGIN;',
    '',
  ];
  for (const r of rows) {
    const tag = dollarTag(r.prompt_md);
    lines.push(
      `INSERT INTO agent_prompt_versions (agent, version, prompt_md, weight, active, status)`,
      `VALUES ('${r.agent}', '${r.version}', ${tag}${r.prompt_md}${tag}, ${r.weight}, ${r.active}, '${r.status}')`,
      `ON CONFLICT (agent, version) DO UPDATE SET`,
      `  prompt_md  = EXCLUDED.prompt_md,`,
      `  weight     = EXCLUDED.weight,`,
      `  active     = EXCLUDED.active,`,
      `  status     = EXCLUDED.status,`,
      `  updated_at = NOW();`,
      '',
    );
  }
  lines.push('COMMIT;', '');
  return lines.join('\n');
}

async function main() {
  const dryRun = process.argv.includes('--dry-run');

  let rows;
  try {
    rows = buildRows();
  } catch (err) {
    console.error(`[register-prompts] FAIL: ${err.message}`);
    process.exit(1);
  }

  console.log(`[register-prompts] built ${rows.length} rows (full + compact × ${AGENTS.length} agents):`);
  for (const r of rows) {
    console.log(`   • ${r.agent}/${r.version} — ${r.prompt_md.length} chars`);
  }

  if (dryRun) {
    console.log('[register-prompts] --dry-run: no database writes performed.');
    process.exit(0);
  }

  const emitArg = process.argv.find((a) => a === '--emit-sql' || a.startsWith('--emit-sql='));
  if (emitArg) {
    let outPath = emitArg.includes('=') ? emitArg.split('=').slice(1).join('=') : process.argv[process.argv.indexOf(emitArg) + 1];
    if (!outPath) outPath = path.join(ROOT, 'scripts', 'register-prompt-versions.generated.sql');
    const resolved = path.resolve(ROOT, outPath);
    fs.writeFileSync(resolved, emitSql(rows), 'utf8');
    console.log(`[register-prompts] --emit-sql: wrote idempotent SQL → ${path.relative(ROOT, resolved)}`);
    process.exit(0);
  }

  const connectionString = resolveConnectionString();
  if (!connectionString) {
    console.log(
      '[register-prompts] SKIP: no direct Postgres connection string found.\n' +
        '        Set SMOKE_DATABASE_URL, DIRECT_URL, or DATABASE_URL to a real\n' +
        '        Postgres/Supabase pooler URL to register prompt versions,\n' +
        '        or re-run with --dry-run to preview the rows.'
    );
    process.exit(0);
  }

  let Client;
  try {
    ({ Client } = require('pg'));
  } catch (err) {
    console.error('[register-prompts] FAIL: the "pg" package is not installed.', err.message);
    process.exit(1);
  }

  const useSsl =
    /supabase\.(co|com|in)/i.test(connectionString) || process.env.PGSSLMODE === 'require';
  const client = new Client({
    connectionString,
    ssl: useSsl ? { rejectUnauthorized: false } : undefined,
  });

  try {
    await client.connect();
  } catch (err) {
    console.error('[register-prompts] FAIL: could not connect to the database:', err.message);
    process.exit(1);
  }

  try {
    for (const r of rows) {
      await client.query(UPSERT_SQL, [r.agent, r.version, r.prompt_md, r.weight, r.active, r.status]);
      console.log(`   ✓ upserted ${r.agent}/${r.version}`);
    }
    console.log(`\n[register-prompts] PASS: ${rows.length} prompt versions registered.`);
    await client.end();
    process.exit(0);
  } catch (err) {
    console.error('\n[register-prompts] FAIL: upsert error:', err.message);
    try {
      await client.end();
    } catch (_) {
      /* ignore */
    }
    process.exit(1);
  }
}

main().catch((err) => {
  console.error('[register-prompts] unexpected error:', err);
  process.exit(1);
});
